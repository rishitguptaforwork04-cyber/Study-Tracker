export function getTodayISO(): string {
  return new Date().toISOString().slice(0, 10);
}

function offsetDate(daysFromToday: number): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + daysFromToday);
  return d.toISOString().slice(0, 10);
}

